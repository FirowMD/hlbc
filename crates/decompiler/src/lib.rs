    #[test]
    fn optimization_profiles_drive_deterministic_verified_lowering_and_traces() {
        let code = Bytecode::from_file("../../data/Empty.hl").unwrap();
        let template = code.function_by_name("main").unwrap();
        let function = synthetic_function(
            template,
            vec![RefType(3)],
            vec![
                Opcode::Int {
                    dst: Reg(0),
                    ptr: hlbc::types::RefInt(0),
                },
                Opcode::SetGlobal {
                    global: hlbc::types::RefGlobal(0),
                    src: Reg(0),
                },
                Opcode::SetGlobal {
                    global: hlbc::types::RefGlobal(0),
                    src: Reg(0),
                },
                Opcode::Ret { ret: Reg(0) },
            ],
        );
        let decompile = |optimization_profile| {
            decompile_code_with_options(
                &code,
                &function,
                DecompileOptions {
                    optimization_profile,
                    trace_optimizations: true,
                    ..DecompileOptions::default()
                },
            )
            .unwrap()
        };
        let fidelity = decompile(OptimizationProfile::Fidelity);
        let readability = decompile(OptimizationProfile::Readability);
        let global_store_count = |statements: &[Statement]| {
            statements
                .iter()
                .filter(|statement| {
                    matches!(raw_statement(statement), Statement::GlobalStore { .. })
                })
                .count()
        };
        assert_eq!(global_store_count(&fidelity.value), 2);
        assert_eq!(global_store_count(&readability.value), 1);

        let trace = readability.optimization_traces.as_ref().unwrap();
        assert_eq!(trace.len(), 1);
        assert_eq!(
            trace[0].passes.len(),
            OptimizationProfile::Readability.pipeline().len()
        );
        assert!(trace[0]
            .passes
            .iter()
            .all(|pass| pass.applied && pass.before_valid && pass.after_valid));
        let repeated = decompile(OptimizationProfile::Readability);
        assert_eq!(
            serde_json::to_string(&readability.optimization_traces).unwrap(),
            serde_json::to_string(&repeated.optimization_traces).unwrap()
        );
    }

    #[test]
    fn array_builder_flushes_ordered_writes_when_the_allocation_escapes() {
        let code = Bytecode::from_file("../../data/Empty.hl").unwrap();
        let mut function = code.function_by_name("main").unwrap().clone();
        function.regs = vec![RefType(3)];
        let mut state = DecompilerState::new(&code, &function, 0, HashSet::new(), HashSet::new());
        let array = Expr::Variable(Reg(0), Some(Str::from("values")));
        state.reg_state.insert(Reg(0), array);
        state.array_builders.insert(
            Reg(0),
            ArrayBuilder {
                element_type: Some(RefType(3)),
                elements: vec![Expr::Unknown("first()".to_owned())],
                temporaries: HashSet::from([Reg(0)]),
                writes: vec![PendingArrayWrite::Array {
                    opcode: 4,
                    index: Expr::Constant(Constant::InlineInt(0)),
                    value: Expr::Unknown("first()".to_owned()),
                }],
            },
        );

        state.flush_escaped_array_builders(&[Reg(0)]);
        assert!(!state.array_builders.contains_key(&Reg(0)));
        assert!(matches!(
            state.statements.as_slice(),
            [Statement::Assign {
                declaration: false,
                variable: Expr::Array(_, _),
                assign: Expr::Unknown(value),
            }] if value == "first()"
        ));
    }

