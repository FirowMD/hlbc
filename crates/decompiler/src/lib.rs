    fn raw_statement(mut statement: &Statement) -> &Statement {
        while let Statement::Provenanced {
            statement: inner, ..
        } = statement
        {
            statement = inner;
        }
        statement
    }

    fn raw_expression(mut expression: &Expr) -> &Expr {
        while let Expr::Provenanced {
            expression: inner, ..
        } = expression
        {
            expression = inner;
        }
        expression
    }

    fn returned_expression(statements: &[Statement]) -> &Expr {
        statements
            .iter()
            .find_map(|statement| match raw_statement(statement) {
                Statement::Return(Some(expression)) => Some(raw_expression(expression)),
                _ => None,
            })
            .expect("decompiled function should return an expression")
    }

    fn contains_statement(
        statements: &[Statement],
        predicate: &dyn Fn(&Statement) -> bool,
    ) -> bool {
        statements.iter().any(|statement| {
            let statement = raw_statement(statement);
            if predicate(statement) {
                return true;
            }
            match statement {
                Statement::IfElse { if_, else_, .. } => {
                    contains_statement(if_, predicate) || contains_statement(else_, predicate)
                }
                Statement::Switch { default, cases, .. } => {
                    contains_statement(default, predicate)
                        || cases
                            .iter()
                            .any(|(_, body)| contains_statement(body, predicate))
                }
                Statement::While { stmts, .. }
                | Statement::DoWhile { stmts, .. }
                | Statement::Try { stmts }
                | Statement::Catch { stmts } => contains_statement(stmts, predicate),
                Statement::TryCatch { try_stmts, catches } => {
                    contains_statement(try_stmts, predicate)
                        || catches
                            .iter()
                            .any(|catch| contains_statement(&catch.stmts, predicate))
                }
                Statement::StateMachine { blocks, .. } => blocks
                    .iter()
                    .any(|block| contains_statement(&block.stmts, predicate)),
                _ => false,
            }
        })
    }

