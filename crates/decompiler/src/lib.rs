#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LoweringCoverage {
    Expression,
    Statement,
    Structural,
    SemanticOnly,
    UnsupportedFallback,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DiagnosticCoverage {
    Validated,
    Contextual,
    Approximation,
    Unsupported,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OpcodeCoverage {
    pub lowering: LoweringCoverage,
    pub diagnostics: DiagnosticCoverage,
}

/// Explicit parser-to-lowering contract. This match intentionally has no
/// wildcard so adding an opcode requires choosing lowering and diagnostics.
pub fn opcode_coverage(opcode: &Opcode) -> OpcodeCoverage {
    use DiagnosticCoverage as D;
    use LoweringCoverage as L;
    let (lowering, diagnostics) = match opcode {
        Opcode::Mov { .. }
        | Opcode::Int { .. }
        | Opcode::Float { .. }
        | Opcode::Bool { .. }
        | Opcode::String { .. }
        | Opcode::Null { .. }
        | Opcode::Add { .. }
        | Opcode::Sub { .. }
        | Opcode::Mul { .. }
        | Opcode::SDiv { .. }
        | Opcode::UDiv { .. }
        | Opcode::SMod { .. }
        | Opcode::UMod { .. }
        | Opcode::Shl { .. }
        | Opcode::SShr { .. }
        | Opcode::UShr { .. }
        | Opcode::And { .. }
        | Opcode::Or { .. }
        | Opcode::Xor { .. }
        | Opcode::Neg { .. }
        | Opcode::Not { .. }
        | Opcode::Incr { .. }
        | Opcode::Decr { .. }
        | Opcode::Call0 { .. }
        | Opcode::Call1 { .. }
        | Opcode::Call2 { .. }
        | Opcode::Call3 { .. }
        | Opcode::Call4 { .. }
        | Opcode::CallN { .. }
        | Opcode::CallMethod { .. }
        | Opcode::CallThis { .. }
        | Opcode::CallClosure { .. }
        | Opcode::StaticClosure { .. }
        | Opcode::InstanceClosure { .. }
        | Opcode::GetGlobal { .. }
        | Opcode::Field { .. }
        | Opcode::GetThis { .. }
        | Opcode::DynGet { .. }
        | Opcode::ToDyn { .. }
        | Opcode::ToSFloat { .. }
        | Opcode::ToUFloat { .. }
        | Opcode::ToInt { .. }
        | Opcode::SafeCast { .. }
        | Opcode::UnsafeCast { .. }
        | Opcode::ToVirtual { .. }
        | Opcode::GetArray { .. }
        | Opcode::New { .. }
        | Opcode::ArraySize { .. }
        | Opcode::EnumAlloc { .. }
        | Opcode::MakeEnum { .. }
        | Opcode::EnumIndex { .. }
        | Opcode::EnumField { .. } => (L::Expression, D::Validated),
        Opcode::Bytes { .. }
        | Opcode::VirtualClosure { .. }
        | Opcode::Type { .. }
        | Opcode::GetType { .. }
        | Opcode::GetTID { .. }
        | Opcode::Ref { .. }
        | Opcode::Unref { .. }
        | Opcode::RefData { .. }
        | Opcode::RefOffset { .. }
        | Opcode::GetI8 { .. }
        | Opcode::GetI16 { .. }
        | Opcode::GetMem { .. } => (L::Expression, D::Contextual),
        Opcode::SetGlobal { .. }
        | Opcode::SetField { .. }
        | Opcode::SetThis { .. }
        | Opcode::DynSet { .. }
        | Opcode::Setref { .. }
        | Opcode::SetArray { .. }
        | Opcode::SetI8 { .. }
        | Opcode::SetI16 { .. }
        | Opcode::SetMem { .. }
        | Opcode::SetEnumField { .. }
        | Opcode::Throw { .. }
        | Opcode::Rethrow { .. } => (L::Statement, D::Validated),
        Opcode::JTrue { .. }
        | Opcode::JFalse { .. }
        | Opcode::JNull { .. }
        | Opcode::JNotNull { .. }
        | Opcode::JSLt { .. }
        | Opcode::JSGte { .. }
        | Opcode::JSGt { .. }
        | Opcode::JSLte { .. }
        | Opcode::JULt { .. }
        | Opcode::JUGte { .. }
        | Opcode::JNotLt { .. }
        | Opcode::JNotGte { .. }
        | Opcode::JEq { .. }
        | Opcode::JNotEq { .. }
        | Opcode::JAlways { .. }
        | Opcode::Switch { .. }
        | Opcode::Label
        | Opcode::Ret { .. }
        | Opcode::Trap { .. }
        | Opcode::Catch { .. } => (L::Structural, D::Contextual),
        Opcode::EndTrap { .. } => (L::Structural, D::Contextual),
        Opcode::NullCheck { .. } | Opcode::Assert | Opcode::Prefetch { .. } | Opcode::Nop => {
            (L::SemanticOnly, D::Validated)
        }
        Opcode::Asm { .. } => (L::UnsupportedFallback, D::Unsupported),
    };
    OpcodeCoverage {
        lowering,
        diagnostics,
    }
}

fn hashlink_function_index(function: &Function) -> usize {
    function.findex.0
}

fn bytes_entry(code: &Bytecode, reference: hlbc::types::RefBytes) -> Option<Vec<u8>> {
    let (bytes, positions) = code.bytes.as_ref()?;
    let start = *positions.get(reference.0)?;
    let end = positions
        .get(reference.0 + 1)
        .copied()
        .unwrap_or(bytes.len());
    bytes.get(start..end).map(<[u8]>::to_vec)
}

enum ExprCtx {
    Constructor {
        reg: Reg,
        pos: usize,
    },
    Anonymous {
        pos: usize,
        fields: BTreeMap<RefField, Expr>,
        remaining: usize,
    },
}

struct DecompilerState<'c> {
    // Flat semantic statements. CFG regions provide all nesting.
    statements: Vec<Statement>,
    // Expression values for each registers
    reg_state: HashMap<Reg, Expr>,
    // For parsing statements made of multiple instructions like constructor calls and anonymous structures
    // TODO move this to another pass on the generated ast
    expr_ctx: Vec<ExprCtx>,
    // Variable names we already declared
    seen: HashSet<Str>,
    f: &'c Function,
    code: &'c Bytecode,
    function_index: usize,
    diagnostics: Vec<Diagnostic>,
    current_opcode: usize,
    flat_statements: BTreeMap<usize, Vec<Statement>>,
    branch_conditions: BTreeMap<usize, Expr>,
    switch_args: BTreeMap<usize, Expr>,
    returns: BTreeMap<usize, Option<Expr>>,
    throws: BTreeMap<usize, Expr>,
}

impl<'c> DecompilerState<'c> {
    fn new(code: &'c Bytecode, f: &'c Function, function_index: usize) -> DecompilerState<'c> {
        let mut reg_state = HashMap::with_capacity(f.regs.len());
        let expr_ctx = Vec::new();
        let mut seen = HashSet::new();

        let mut start = 0;
        // First argument / First register is 'this'
        if f.is_method() || code.get(f.name) == "__constructor__" {
            reg_state.insert(Reg(0), cst_this());
            start = 1;
        }

        // Initialize register state with the function arguments
        for i in start..f.ty(code).args.len() {
            let name = f.arg_name(code, i - start);
            reg_state.insert(Reg(i as u32), Expr::Variable(Reg(i as u32), name.clone()));
            if let Some(name) = name {
                seen.insert(name);
            }
        }

        Self {
            statements: Vec::new(),
            reg_state,
            expr_ctx,
            seen,
            f,
            code,
            function_index,
            diagnostics: Vec::new(),
            current_opcode: 0,
            flat_statements: BTreeMap::new(),
            branch_conditions: BTreeMap::new(),
            switch_args: BTreeMap::new(),
            returns: BTreeMap::new(),
            throws: BTreeMap::new(),
        }
    }

    fn push_stmt(&mut self, stmt: Statement) {
        self.flat_statements
            .entry(self.current_opcode)
            .or_default()
            .push(stmt.clone());
        self.statements.push(stmt);
    }

    fn diagnose(
        &mut self,
        severity: DiagnosticSeverity,
        opcode_index: usize,
        opcode: &Opcode,
        message: impl Into<String>,
    ) {
        self.diagnostics.push(Diagnostic::for_opcode(
            severity,
            self.code,
            self.function_index,
            self.f,
            opcode_index,
            opcode,
            message,
        ));
    }

    fn unhandled(&mut self, opcode_index: usize, opcode: &Opcode, message: impl Into<String>) {
        self.diagnose(
            DiagnosticSeverity::Unsupported,
            opcode_index,
            opcode,
            message,
        );
        self.push_stmt(Statement::UnhandledOpcode {
            opcode: opcode.clone(),
            provenance: Provenance::opcode(self.function_index, opcode_index),
        });
    }

    fn check_type(
        &mut self,
        opcode_index: usize,
        opcode: &Opcode,
        actual: RefType,
        expected: &'static str,
        matches: impl FnOnce(&Type) -> bool,
    ) {
        if self
            .code
            .types
            .get(actual.0)
            .map_or(false, |ty| !matches(ty))
        {
            self.diagnose(
                DiagnosticSeverity::Approximation,
                opcode_index,
                opcode,
                format!("type t{} does not match expected {expected}", actual.0),
            );
        }
    }

    // Update the register state and create a statement depending on inline rules
    fn push_expr(&mut self, i: usize, dst: Reg, expr: Expr) {
        let name = self.f.var_name(self.code, i);
        // Inline check
        if name.is_none() {
            self.reg_state.insert(dst, expr);
        } else {
            self.reg_state
                .insert(dst, Expr::Variable(dst, name.clone()));
            if let Some(variable_name) = name.clone() {
                let declaration = self.seen.insert(variable_name);
                self.push_stmt(Statement::Assign {
                    declaration,
                    variable: Expr::Variable(dst, name),
                    assign: expr,
                });
            }
        }
    }

    // Get the expr for a register
    fn expr(&self, reg: Reg) -> Expr {
        self.reg_state
            .get(&reg)
            .cloned()
            .unwrap_or_else(|| Expr::Unknown("missing expr".to_owned()))
    }

    /// Expands the expression of many registers
    fn args_expr(&self, args: &[Reg]) -> Vec<Expr> {
        args.iter().map(|&r| self.expr(r)).collect()
    }

    /// Push a call to a function, which might be a constructor call.
    fn push_call(&mut self, i: usize, dst: Reg, fun: RefFun, args: &[Reg]) {
        if let Some(&ExprCtx::Constructor { reg, pos }) = self.expr_ctx.last() {
            if args.first().copied() == Some(reg) {
                self.push_expr(
                    pos,
                    reg,
                    Expr::Constructor(ConstructorCall::new(
                        self.f.regtype(reg),
                        self.args_expr(&args[1..]),
                    )),
                );
                self.expr_ctx.pop();
            }
        } else {
            self.push_stmt(comment(fun.display::<EnhancedFmt>(self.code).to_string()));
            let call = if let Some((func, true)) =
                fun.as_fn(self.code).map(|func| (func, func.is_method()))
            {
                if let Some(receiver) = args.first() {
                    call(
                        Expr::Field(Box::new(self.expr(*receiver)), func.name(self.code)),
                        self.args_expr(&args[1..]),
                    )
                } else {
                    call_fun(fun, Vec::new())
                }
            } else {
                call_fun(fun, self.args_expr(args))
            };
            if fun.ty(self.code).ret.is_void() {
                self.push_stmt(stmt(call));
            } else {
                self.push_expr(i, dst, call);
            }
        }
    }

    /// Process a jmp instruction, might be the exit condition of a loop or an if
    fn push_jmp(&mut self, i: usize, _offset: i32, cond: Expr, _opcode: &Opcode) {
        self.branch_conditions.insert(i, not(cond.clone()));
    }
}

/// Decompile a function code to a list of [Statement]s.
/// This pass lowers opcode semantics into flat per-opcode statements and expressions.
struct LegacyOutput {
    statements: Vec<Statement>,
    diagnostics: Vec<Diagnostic>,
    flat: FlatOutput,
}

#[derive(Debug, Clone, Default)]
pub(crate) struct FlatOutput {
    pub(crate) statements: BTreeMap<usize, Vec<Statement>>,
    pub(crate) branch_conditions: BTreeMap<usize, Expr>,
    pub(crate) switch_args: BTreeMap<usize, Expr>,
    pub(crate) returns: BTreeMap<usize, Option<Expr>>,
    pub(crate) throws: BTreeMap<usize, Expr>,
}

fn decompile_code_legacy(
    code: &Bytecode,
    f: &Function,
    function_index: usize,
    typed_ir: &ir::TypedIr,
) -> LegacyOutput {
    let mut compatibility_function = f.clone();
    compatibility_function.ops = typed_ir.bytecode_compatibility_stream();
    decompile_code_legacy_inner(
        code,
        &compatibility_function,
        function_index,
        &mut HashSet::new(),
    )
}

fn decompile_code_legacy_via_ir(
    code: &Bytecode,
    function: &Function,
    function_index: usize,
    active_functions: &mut HashSet<usize>,
) -> LegacyOutput {
    let graph = match ControlFlowGraph::build_with_index(function, function_index) {
        Ok(graph) => graph,
        Err(error) => {
            return LegacyOutput {
                statements: function
                    .ops
                    .iter()
                    .enumerate()
                    .map(|(opcode_index, opcode)| Statement::UnhandledOpcode {
                        opcode: opcode.clone(),
                        provenance: Provenance::opcode(function_index, opcode_index),
                    })
                    .collect(),
                diagnostics: vec![Diagnostic::fatal(function_index, error.to_string())],
                flat: FlatOutput::default(),
            };
        }
    };
    let typed_ir = ir::TypedIr::build_with_cfg(code, function, graph);
    let mut compatibility_function = function.clone();
    compatibility_function.ops = typed_ir.value.bytecode_compatibility_stream();
    let mut output = decompile_code_legacy_inner(
        code,
        &compatibility_function,
        function_index,
        active_functions,
    );
    output.diagnostics.splice(0..0, typed_ir.diagnostics);
    output
}

fn decompile_code_legacy_inner(
    code: &Bytecode,
    f: &Function,
    function_index: usize,
    active_functions: &mut HashSet<usize>,
) -> LegacyOutput {
    if !active_functions.insert(function_index) {
        return LegacyOutput {
            statements: Vec::new(),
            diagnostics: vec![Diagnostic::fatal(
                function_index,
                "recursive decompilation entry was stopped",
            )],
            flat: FlatOutput::default(),
        };
    }
    let mut state = DecompilerState::new(code, f, function_index);

    let iter = f.ops.iter().enumerate();
    for (i, o) in iter {
        state.current_opcode = i;
        // Opcodes are grouped by semantic
        // Control flow first because they are the most important
        match o {
            //region CONTROL FLOW
            &Opcode::JTrue { cond, offset } => state.push_jmp(i, offset, not(state.expr(cond)), o),
            &Opcode::JFalse { cond, offset } => state.push_jmp(i, offset, state.expr(cond), o),
            &Opcode::JNull { reg, offset } => {
                state.push_jmp(i, offset, noteq(state.expr(reg), cst_null()), o)
            }
            &Opcode::JNotNull { reg, offset } => {
                state.push_jmp(i, offset, eq(state.expr(reg), cst_null()), o)
            }
            &Opcode::JSGte { a, b, offset } | &Opcode::JUGte { a, b, offset } => {
                state.push_jmp(i, offset, gt(state.expr(b), state.expr(a)), o)
            }
            &Opcode::JSGt { a, b, offset } => {
                state.push_jmp(i, offset, gte(state.expr(b), state.expr(a)), o)
            }
            &Opcode::JSLte { a, b, offset } => {
                state.push_jmp(i, offset, lt(state.expr(b), state.expr(a)), o)
            }
            &Opcode::JSLt { a, b, offset } | &Opcode::JULt { a, b, offset } => {
                state.push_jmp(i, offset, lte(state.expr(b), state.expr(a)), o)
            }
            &Opcode::JEq { a, b, offset } => {
                state.push_jmp(i, offset, noteq(state.expr(a), state.expr(b)), o)
            }
            &Opcode::JNotEq { a, b, offset } => {
                state.push_jmp(i, offset, eq(state.expr(a), state.expr(b)), o)
            }
            &Opcode::JNotLt { a, b, offset } => {
                state.push_jmp(i, offset, lt(state.expr(a), state.expr(b)), o)
            }
            &Opcode::JNotGte { a, b, offset } => {
                state.push_jmp(i, offset, gte(state.expr(a), state.expr(b)), o)
            }
            Opcode::JAlways { .. } => {}
            Opcode::Switch { reg, offsets, end } => {
                state.switch_args.insert(i, state.expr(*reg));
                let _ = (offsets, end);
            }
            Opcode::Label => {}
            &Opcode::Ret { ret } => {
                state.returns.insert(
                    i,
                    if f.regtype(ret).is_void() {
                        None
                    } else {
                        Some(state.expr(ret))
                    },
                );
                state.push_stmt(Statement::Return(
                    state.returns.get(&i).cloned().unwrap_or(None),
                ));
            }
            //endregion

            //region EXCEPTIONS
            &Opcode::Throw { exc } | &Opcode::Rethrow { exc } => {
                state.throws.insert(i, state.expr(exc));
                state.push_stmt(Statement::Throw(state.expr(exc)));
            }
            Opcode::Trap { .. } => {}
            Opcode::EndTrap { .. } => {}
            &Opcode::NullCheck { reg } => {
                state.push_stmt(Statement::RuntimeCheck(RuntimeCheck::Null(state.expr(reg))));
            }
            Opcode::Assert => {
                state.push_stmt(Statement::RuntimeCheck(RuntimeCheck::Assert));
            }
            //endregion

            //region CONSTANTS
            &Opcode::Int { dst, ptr } => {
                state.push_expr(i, dst, cst_int(ptr));
            }
            &Opcode::Float { dst, ptr } => {
                state.push_expr(i, dst, cst_float(ptr));
            }
            &Opcode::Bool { dst, value } => {
                state.push_expr(i, dst, cst_bool(value));
            }
            &Opcode::Bytes { dst, ptr } => match bytes_entry(code, ptr) {
                Some(bytes) => {
                    state.check_type(i, o, f.regtype(dst), "Bytes", |ty| {
                        matches!(ty, Type::Bytes)
                    });
                    state.push_expr(
                        i,
                        dst,
                        Expr::Bytes(BytesLiteral {
                            reference: ptr,
                            bytes,
                            provenance: Provenance::opcode(function_index, i),
                        }),
                    );
                }
                None => state.unhandled(i, o, "bytes constant could not be resolved"),
            },
            &Opcode::String { dst, ptr } => {
                state.push_expr(i, dst, cst_string(ptr));
            }
            &Opcode::Null { dst } => {
                state.push_expr(i, dst, cst_null());
            }
            //endregion

            //region OPERATORS
            &Opcode::Mov { dst, src } => {
                state.push_expr(i, dst, state.expr(src));
                // Workaround for when the instructions after this one use dst and src interchangeably.
                state
                    .reg_state
                    .insert(src, Expr::Variable(dst, f.var_name(code, i)));
            }
            &Opcode::Add { dst, a, b } => {
                state.push_expr(i, dst, add(state.expr(a), state.expr(b)));
            }
            &Opcode::Sub { dst, a, b } => {
                state.push_expr(i, dst, sub(state.expr(a), state.expr(b)));
            }
            &Opcode::Mul { dst, a, b } => {
                state.push_expr(i, dst, mul(state.expr(a), state.expr(b)));
            }
            &Opcode::SDiv { dst, a, b } | &Opcode::UDiv { dst, a, b } => {
                state.push_expr(i, dst, div(state.expr(a), state.expr(b)));
            }
            &Opcode::SMod { dst, a, b } | &Opcode::UMod { dst, a, b } => {
                state.push_expr(i, dst, modulo(state.expr(a), state.expr(b)));
            }
            &Opcode::Shl { dst, a, b } => {
                state.push_expr(i, dst, shl(state.expr(a), state.expr(b)));
            }
            &Opcode::SShr { dst, a, b } | &Opcode::UShr { dst, a, b } => {
                state.push_expr(i, dst, shr(state.expr(a), state.expr(b)));
            }
            &Opcode::And { dst, a, b } => {
                state.push_expr(i, dst, and(state.expr(a), state.expr(b)));
            }
            &Opcode::Or { dst, a, b } => {
                state.push_expr(i, dst, or(state.expr(a), state.expr(b)));
            }
            &Opcode::Xor { dst, a, b } => {
                state.push_expr(i, dst, xor(state.expr(a), state.expr(b)));
            }
            &Opcode::Neg { dst, src } => {
                state.push_expr(i, dst, neg(state.expr(src)));
            }
            &Opcode::Not { dst, src } => {
                state.push_expr(i, dst, not(state.expr(src)));
            }
            &Opcode::Incr { dst } => {
                // FIXME sometimes it should be an expression
                state.push_stmt(stmt(incr(state.expr(dst))));
            }
            &Opcode::Decr { dst } => {
                state.push_stmt(stmt(decr(state.expr(dst))));
            }
            //endregion

            //region CALLS
            &Opcode::Call0 { dst, fun } => {
                if fun.ty(code).ret.is_void() {
                    state.push_stmt(stmt(call_fun(fun, Vec::new())));
                } else {
                    state.push_expr(i, dst, call_fun(fun, Vec::new()));
                }
            }
            &Opcode::Call1 { dst, fun, arg0 } => {
                state.push_call(i, dst, fun, &[arg0]);
            }
            &Opcode::Call2 {
                dst,
                fun,
                arg0,
                arg1,
            } => {
                state.push_call(i, dst, fun, &[arg0, arg1]);
            }
            &Opcode::Call3 {
                dst,
                fun,
                arg0,
                arg1,
                arg2,
            } => {
                state.push_call(i, dst, fun, &[arg0, arg1, arg2]);
            }
            &Opcode::Call4 {
                dst,
                fun,
                arg0,
                arg1,
                arg2,
                arg3,
            } => {
                state.push_call(i, dst, fun, &[arg0, arg1, arg2, arg3]);
            }
            Opcode::CallN { dst, fun, args } => {
                if let Some(&ExprCtx::Constructor { reg, pos }) = state.expr_ctx.last() {
                    if args.first().copied() == Some(reg) {
                        state.push_expr(
                            pos,
                            reg,
                            Expr::Constructor(ConstructorCall::new(
                                f.regtype(reg),
                                state.args_expr(&args[1..]),
                            )),
                        );
                    }
                } else {
                    state.push_stmt(comment(fun.display::<EnhancedFmt>(code).to_string()));
                    let call = call_fun(*fun, state.args_expr(args));
                    if fun.ty(code).ret.is_void() {
                        state.push_stmt(stmt(call));
                    } else {
                        state.push_expr(i, *dst, call);
                    }
                }
            }
            Opcode::CallMethod { dst, field, args } => {
                let Some(receiver) = args.first().copied() else {
                    state.unhandled(i, o, "CallMethod has no receiver argument");
                    continue;
                };
                let call = call(
                    ast::field(state.expr(receiver), f.regtype(receiver), *field, code),
                    state.args_expr(&args[1..]),
                );
                if f.regtype(receiver)
                    .method(field.0, code)
                    .and_then(|p| p.findex.as_fn(code))
                    .map(|fun| fun.ty(code).ret.is_void())
                    .unwrap_or(false)
                {
                    state.push_stmt(stmt(call));
                } else {
                    state.push_expr(i, *dst, call);
                }
            }
            Opcode::CallThis { dst, field, args } => {
                match f
                    .regs
                    .first()
                    .and_then(|receiver| receiver.method(field.0, code))
                {
                    Some(method) => {
                        let call = call(
                            Expr::Field(Box::new(cst_this()), method.name(code)),
                            state.args_expr(args),
                        );
                        if method
                            .findex
                            .as_fn(code)
                            .map(|fun| fun.ty(code).ret.is_void())
                            .unwrap_or(false)
                        {
                            state.push_stmt(stmt(call));
                        } else {
                            state.push_expr(i, *dst, call);
                        }
                    }
                    None => {
                        state.diagnose(
                            DiagnosticSeverity::Approximation,
                            i,
                            o,
                            "method binding could not be resolved",
                        );
                        state.push_expr(
                            i,
                            *dst,
                            Expr::Unknown("Unresolved method call".to_string()),
                        );
                    }
                }
            }
            Opcode::CallClosure { dst, fun, args } => {
                let call = call(state.expr(*fun), state.args_expr(args));
                if f.regtype(*fun)
                    .as_fun(code)
                    .map(|ty| ty.ret.is_void())
                    .unwrap_or(false)
                {
                    state.push_stmt(stmt(call));
                } else {
                    state.push_expr(i, *dst, call);
                }
            }
            //endregion

            //region CLOSURES
            &Opcode::StaticClosure { dst, fun } => {
                state.push_stmt(comment(format!(
                    "closure : {}",
                    fun.display::<EnhancedFmt>(code)
                )));
                let expression = match fun.as_fn(code) {
                    Some(function) => {
                        let nested_index = hashlink_function_index(function);
                        if active_functions.contains(&nested_index) {
                            state.diagnose(
                                DiagnosticSeverity::Approximation,
                                i,
                                o,
                                "recursive closure body retained as a function reference",
                            );
                            Expr::FunRef(fun)
                        } else {
                            let nested = decompile_code_legacy_via_ir(
                                code,
                                function,
                                nested_index,
                                active_functions,
                            );
                            state.diagnostics.extend(nested.diagnostics);
                            Expr::Closure(fun, nested.statements)
                        }
                    }
                    None => Expr::Unknown("Unresolved closure function".to_string()),
                };
                state.push_expr(i, dst, expression);
            }
            &Opcode::InstanceClosure { dst, obj, fun } => {
                state.push_stmt(comment(format!(
                    "closure : {}",
                    fun.display::<EnhancedFmt>(code)
                )));
                match &code[f[obj]] {
                    // This is an anonymous enum holding the capture for the closure
                    Type::Enum { .. } => match fun.as_fn(code) {
                        Some(function) => {
                            let nested_index = hashlink_function_index(function);
                            if active_functions.contains(&nested_index) {
                                state.diagnose(
                                    DiagnosticSeverity::Approximation,
                                    i,
                                    o,
                                    "recursive closure body retained as a function reference",
                                );
                                state.push_expr(i, dst, Expr::FunRef(fun));
                            } else {
                                let nested = decompile_code_legacy_via_ir(
                                    code,
                                    function,
                                    nested_index,
                                    active_functions,
                                );
                                state.diagnostics.extend(nested.diagnostics);
                                state.push_expr(i, dst, Expr::Closure(fun, nested.statements));
                            }
                        }
                        None => state.unhandled(i, o, "closure function reference is unresolved"),
                    },
                    _ => {
                        state.push_expr(
                            i,
                            dst,
                            Expr::Field(Box::new(state.expr(obj)), fun.name(code)),
                        );
                    }
                }
            }
            &Opcode::VirtualClosure { dst, obj, field } => {
                let receiver_type = f.regtype(obj);
                match receiver_type.method(field.0, code) {
                    Some(prototype) => match code.safe_get_ref_fun(prototype.findex) {
                        Some(target) => {
                            let target_type = match target {
                                FunPtr::Fun(function) => function.t,
                                FunPtr::Native(native) => native.t,
                            };
                            state.check_type(i, o, f.regtype(dst), "callable", |ty| {
                                matches!(ty, Type::Fun(_) | Type::Method(_))
                            });
                            state.push_expr(
                                i,
                                dst,
                                Expr::VirtualClosure {
                                    receiver: Box::new(state.expr(obj)),
                                    method: prototype.name(code),
                                    target: prototype.findex,
                                    callable_type: f.regtype(dst),
                                    target_type,
                                },
                            );
                        }
                        None => state.unhandled(
                            i,
                            o,
                            format!(
                                "virtual closure target f@{} is unresolved",
                                prototype.findex.0
                            ),
                        ),
                    },
                    None => state.unhandled(
                        i,
                        o,
                        format!(
                            "virtual closure prototype {} is unresolved for receiver type t{}",
                            field.0, receiver_type.0
                        ),
                    ),
                }
            }
            //endregion

            //region ACCESSES
            &Opcode::GetGlobal { dst, global } => {
                // Is a string
                if f[dst].0 == 13 {
                    state.push_expr(
                        i,
                        dst,
                        cst_string(RefString(
                            code.globals_initializers
                                .get(&global)
                                .and_then(|&x| {
                                    code.constants
                                        .as_ref()
                                        .and_then(|constants| constants.get(x))
                                        .and_then(|constant| constant.fields.first().copied())
                                })
                                .unwrap_or(0),
                        )),
                    );
                } else {
                    match &code[f[dst]] {
                        Type::Obj(obj) | Type::Struct(obj) => {
                            state.push_expr(
                                i,
                                dst,
                                Expr::Variable(dst, Some(code[obj.name].to_owned())),
                            );
                        }
                        Type::Enum { .. } => {
                            state.diagnose(
                                DiagnosticSeverity::Approximation,
                                i,
                                o,
                                "global enum value could not be resolved",
                            );
                            state.push_expr(
                                i,
                                dst,
                                Expr::Unknown("unknown enum variant".to_owned()),
                            );
                        }
                        _ => state.unhandled(i, o, "global value type is not representable"),
                    }
                }
            }
            &Opcode::SetGlobal { global, src } => {
                state.push_stmt(Statement::GlobalStore {
                    global,
                    global_type: code.globals[global.0],
                    value: state.expr(src),
                });
            }
            &Opcode::Field { dst, obj, field } => {
                state.push_expr(
                    i,
                    dst,
                    ast::field(state.expr(obj), f.regtype(obj), field, code),
                );
            }
            &Opcode::SetField { obj, field, src } => {
                let ctx = state.expr_ctx.pop();
                // Might be a SetField for an anonymous structure
                if let Some(ExprCtx::Anonymous {
                    pos,
                    mut fields,
                    mut remaining,
                }) = ctx
                {
                    fields.insert(field, state.expr(src));
                    remaining -= 1;
                    // If we filled all the structure fields, we emit an expr
                    if remaining == 0 {
                        state.push_expr(pos, obj, Expr::Anonymous(f.regtype(obj), fields));
                    } else {
                        state.expr_ctx.push(ExprCtx::Anonymous {
                            pos,
                            fields,
                            remaining,
                        });
                    }
                } else if let Some(ctx) = ctx {
                    state.expr_ctx.push(ctx);
                } else {
                    // Otherwise this is just a normal field set
                    state.push_stmt(Statement::Assign {
                        declaration: false,
                        variable: ast::field(state.expr(obj), f.regtype(obj), field, code),
                        assign: state.expr(src),
                    });
                }
            }
            &Opcode::GetThis { dst, field } => {
                state.push_expr(i, dst, ast::field(cst_this(), f.regs[0], field, code));
            }
            &Opcode::SetThis { field, src } => {
                state.push_stmt(Statement::Assign {
                    declaration: false,
                    variable: ast::field(cst_this(), f.regs[0], field, code),
                    assign: state.expr(src),
                });
            }
            &Opcode::DynGet { dst, obj, field } => {
                state.push_expr(i, dst, array(state.expr(obj), cst_string(field)));
            }
            &Opcode::DynSet { obj, field, src } => {
                state.push_stmt(Statement::Assign {
                    declaration: false,
                    variable: array(state.expr(obj), cst_string(field)),
                    assign: state.expr(src),
                });
            }
            //endregion

            //region VALUES
            &Opcode::ToDyn { dst, src }
            | &Opcode::ToSFloat { dst, src }
            | &Opcode::ToUFloat { dst, src }
            | &Opcode::ToInt { dst, src }
            | &Opcode::SafeCast { dst, src }
            | &Opcode::UnsafeCast { dst, src }
            | &Opcode::ToVirtual { dst, src } => {
                state.push_expr(i, dst, state.expr(src));
            }
            &Opcode::Type { dst, ty } => {
                state.check_type(i, o, f.regtype(dst), "Type", |ty| matches!(ty, Type::Type));
                state.push_expr(
                    i,
                    dst,
                    Expr::TypeValue {
                        ty,
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::GetType { dst, src } => {
                state.check_type(i, o, f.regtype(dst), "Type", |ty| matches!(ty, Type::Type));
                state.push_expr(
                    i,
                    dst,
                    Expr::RuntimeType {
                        value: Box::new(state.expr(src)),
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::GetTID { dst, src } => {
                state.check_type(i, o, f.regtype(dst), "I32", |ty| matches!(ty, Type::I32));
                state.push_expr(
                    i,
                    dst,
                    Expr::TypeId {
                        value: Box::new(state.expr(src)),
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::Ref { dst, src } => {
                let reference_type = f.regtype(dst);
                state.check_type(
                    i,
                    o,
                    reference_type,
                    "Ref of source type",
                    |ty| matches!(ty, Type::Ref(inner) if *inner == f.regtype(src)),
                );
                state.push_expr(
                    i,
                    dst,
                    Expr::Reference {
                        source: src,
                        value: Box::new(state.expr(src)),
                        reference_type,
                    },
                );
            }
            &Opcode::Unref { dst, src } => {
                state.check_type(
                    i,
                    o,
                    f.regtype(src),
                    "Ref of result type",
                    |ty| matches!(ty, Type::Ref(inner) if *inner == f.regtype(dst)),
                );
                state.push_expr(
                    i,
                    dst,
                    Expr::Dereference {
                        reference: Box::new(state.expr(src)),
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::Setref { dst, value } => {
                state.check_type(
                    i,
                    o,
                    f.regtype(dst),
                    "Ref of stored value type",
                    |ty| matches!(ty, Type::Ref(inner) if *inner == f.regtype(value)),
                );
                state.push_stmt(Statement::ReferenceStore {
                    reference: state.expr(dst),
                    value: state.expr(value),
                    value_type: f.regtype(value),
                });
            }
            &Opcode::RefData { dst, src } => {
                let reference_type = f.regtype(dst);
                state.check_type(i, o, reference_type, "Ref", |ty| matches!(ty, Type::Ref(_)));
                state.check_type(i, o, f.regtype(src), "Array", |ty| {
                    matches!(ty, Type::Array)
                });
                state.push_expr(
                    i,
                    dst,
                    Expr::ReferenceData {
                        array: Box::new(state.expr(src)),
                        reference_type,
                    },
                );
            }
            &Opcode::RefOffset { dst, reg, offset } => {
                let reference_type = f.regtype(dst);
                let element_type = match code.types.get(reference_type.0) {
                    Some(Type::Ref(element_type)) => *element_type,
                    _ => {
                        state.diagnose(
                            DiagnosticSeverity::Approximation,
                            i,
                            o,
                            "RefOffset destination is not a reference type",
                        );
                        reference_type
                    }
                };
                state.check_type(
                    i,
                    o,
                    f.regtype(reg),
                    "matching Ref type",
                    |ty| matches!(ty, Type::Ref(inner) if *inner == element_type),
                );
                state.check_type(i, o, f.regtype(offset), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.push_expr(
                    i,
                    dst,
                    Expr::ReferenceOffset {
                        reference: Box::new(state.expr(reg)),
                        offset: Box::new(state.expr(offset)),
                        reference_type,
                        element_type,
                    },
                );
            }
            &Opcode::New { dst } => {
                // Constructor analysis
                match &code[f[dst]] {
                    Type::Obj(_) | Type::Struct(_) => {
                        state
                            .expr_ctx
                            .push(ExprCtx::Constructor { reg: dst, pos: i });
                    }
                    Type::Virtual { fields } => {
                        state.expr_ctx.push(ExprCtx::Anonymous {
                            pos: i,
                            fields: BTreeMap::new(),
                            remaining: fields.len(),
                        });
                    }
                    _ => {
                        state.push_expr(
                            i,
                            dst,
                            Expr::Constructor(ConstructorCall::new(f.regtype(dst), Vec::new())),
                        );
                    }
                }
            }
            //endregion

            //region ENUMS
            &Opcode::EnumAlloc { dst, construct } => {
                state.push_expr(
                    i,
                    dst,
                    Expr::EnumConstr(f.regtype(dst), construct, Vec::new()),
                );
            }
            Opcode::MakeEnum {
                dst,
                construct,
                args,
            } => {
                state.push_expr(
                    i,
                    *dst,
                    Expr::EnumConstr(f.regtype(*dst), *construct, state.args_expr(args)),
                );
            }
            &Opcode::EnumIndex { dst, value } => {
                state.push_expr(i, dst, Expr::EnumIndex(Box::new(state.expr(value))));
                //state.push_expr(i, dst, state.expr(value));
            }
            &Opcode::EnumField {
                dst,
                value,
                construct: _,
                field,
            } => {
                state.push_expr(
                    i,
                    dst,
                    Expr::Field(Box::new(state.expr(value)), Str::from(field.0.to_string())),
                );
            }
            &Opcode::SetEnumField { value, field, src } => match state.expr(value) {
                Expr::Variable(_, _) => {
                    state.push_stmt(Statement::Assign {
                        declaration: false,
                        variable: Expr::Field(
                            Box::new(state.expr(value)),
                            Str::from(field.0.to_string()),
                        ),
                        assign: state.expr(src),
                    });
                }
                _ => {
                    state.push_stmt(comment("closure capture"));
                    state.push_stmt(Statement::Assign {
                        declaration: false,
                        variable: Expr::Field(
                            Box::new(state.expr(value)),
                            Str::from(field.0.to_string()),
                        ),
                        assign: state.expr(src),
                    });
                }
            },
            //endregion

            //region ARRAYS
            &Opcode::ArraySize { dst, array } => {
                state.push_expr(
                    i,
                    dst,
                    Expr::Field(Box::new(state.expr(array)), Str::from("length")),
                );
            }
            &Opcode::GetArray { dst, array, index } => {
                state.push_expr(i, dst, ast::array(state.expr(array), state.expr(index)));
            }
            &Opcode::SetArray { array, index, src } => {
                state.push_stmt(Statement::Assign {
                    declaration: false,
                    variable: ast::array(state.expr(array), state.expr(index)),
                    assign: state.expr(src),
                });
            }
            //endregion

            //region MEM
            &Opcode::GetI8 { dst, bytes, index } => {
                state.check_type(i, o, f.regtype(dst), "UI8", |ty| matches!(ty, Type::UI8));
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.push_expr(
                    i,
                    dst,
                    Expr::MemoryLoad {
                        memory_type: MemoryType::U8,
                        bytes: Box::new(state.expr(bytes)),
                        index: Box::new(state.expr(index)),
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::GetI16 { dst, bytes, index } => {
                state.check_type(i, o, f.regtype(dst), "UI16", |ty| matches!(ty, Type::UI16));
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.push_expr(
                    i,
                    dst,
                    Expr::MemoryLoad {
                        memory_type: MemoryType::U16,
                        bytes: Box::new(state.expr(bytes)),
                        index: Box::new(state.expr(index)),
                        result_type: f.regtype(dst),
                    },
                );
            }
            &Opcode::GetMem { dst, bytes, index } => {
                let result_type = f.regtype(dst);
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.push_expr(
                    i,
                    dst,
                    Expr::MemoryLoad {
                        memory_type: MemoryType::Typed(result_type),
                        bytes: Box::new(state.expr(bytes)),
                        index: Box::new(state.expr(index)),
                        result_type,
                    },
                );
            }
            &Opcode::SetI8 { bytes, index, src } => {
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.check_type(i, o, f.regtype(src), "integer", |ty| {
                    matches!(ty, Type::UI8 | Type::UI16 | Type::I32 | Type::I64)
                });
                state.push_stmt(Statement::MemoryStore {
                    memory_type: MemoryType::U8,
                    bytes: state.expr(bytes),
                    index: state.expr(index),
                    value: state.expr(src),
                    value_type: f.regtype(src),
                });
            }
            &Opcode::SetI16 { bytes, index, src } => {
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.check_type(i, o, f.regtype(src), "integer", |ty| {
                    matches!(ty, Type::UI8 | Type::UI16 | Type::I32 | Type::I64)
                });
                state.push_stmt(Statement::MemoryStore {
                    memory_type: MemoryType::U16,
                    bytes: state.expr(bytes),
                    index: state.expr(index),
                    value: state.expr(src),
                    value_type: f.regtype(src),
                });
            }
            &Opcode::SetMem { bytes, index, src } => {
                let value_type = f.regtype(src);
                state.check_type(i, o, f.regtype(bytes), "Bytes", |ty| {
                    matches!(ty, Type::Bytes)
                });
                state.check_type(i, o, f.regtype(index), "I32 or I64", |ty| {
                    matches!(ty, Type::I32 | Type::I64)
                });
                state.push_stmt(Statement::MemoryStore {
                    memory_type: MemoryType::Typed(value_type),
                    bytes: state.expr(bytes),
                    index: state.expr(index),
                    value: state.expr(src),
                    value_type,
                });
            }
            //endregion
            Opcode::Prefetch { value, field, mode } => {
                state.push_stmt(Statement::Prefetch {
                    value: state.expr(*value),
                    field: *field,
                    mode: *mode,
                });
            }
            Opcode::Nop => state.push_stmt(Statement::Nop),
            Opcode::Asm { .. } => {
                state.unhandled(i, o, "inline assembly cannot be represented as Haxe")
            }
            Opcode::Catch { .. } => {}
        }
    }
    let diagnostics = std::mem::take(&mut state.diagnostics);
    let mut flat = FlatOutput {
        statements: std::mem::take(&mut state.flat_statements),
        branch_conditions: std::mem::take(&mut state.branch_conditions),
        switch_args: std::mem::take(&mut state.switch_args),
        returns: std::mem::take(&mut state.returns),
        throws: std::mem::take(&mut state.throws),
    };
    let mut statements = std::mem::take(&mut state.statements);

    // AST post processing step !
    // It makes a single pass for all visitors
    post::visit(
        code,
        &mut statements,
        &mut [
            Box::new(post::IfExpressions),
            Box::new(post::StringConcat),
            Box::new(post::Itos),
            Box::new(post::Trace),
        ],
    );
    for statements in flat.statements.values_mut() {
        post::visit(
            code,
            statements,
            &mut [
                Box::new(post::IfExpressions),
                Box::new(post::StringConcat),
                Box::new(post::Itos),
                Box::new(post::Trace),
            ],
        );
    }
    ast::attach_provenance(
        &mut statements,
        Provenance::new(function_index, 0, f.ops.len()),
    );
    active_functions.remove(&function_index);

    LegacyOutput {
        statements,
        diagnostics,
        flat,
    }
}

/// Decompile a function body with best-effort fallback output.
pub fn decompile_code(
    code: &Bytecode,
    function: &Function,
) -> Result<Decompiled<Vec<Statement>>, DecompileError> {
    decompile_code_with_options(code, function, DecompileOptions::default())
}

pub fn decompile_code_with_options(
    code: &Bytecode,
    function: &Function,
    options: DecompileOptions,
) -> Result<Decompiled<Vec<Statement>>, DecompileError> {
    let function_index = hashlink_function_index(function);
    if let Err(error) = code.validate_function(function) {
        let diagnostics = vec![Diagnostic::fatal(
            function_index,
            format!("invalid decompiler input: {error}"),
        )];
        if options.mode == DecompileMode::Strict {
            return Err(DecompileError::new(diagnostics));
        }
        let statements = function
            .ops
            .iter()
            .enumerate()
            .map(|(opcode_index, opcode)| Statement::UnhandledOpcode {
                opcode: opcode.clone(),
                provenance: Provenance::opcode(function_index, opcode_index),
            })
            .collect();
        return Ok(Decompiled::new(statements, diagnostics));
    }
    let graph = match ControlFlowGraph::build_with_index(function, function_index) {
        Ok(graph) => graph,
        Err(error) => {
            let diagnostics = vec![Diagnostic::fatal(function_index, error.to_string())];
            if options.mode == DecompileMode::Strict {
                return Err(DecompileError::new(diagnostics));
            }
            let statements = function
                .ops
                .iter()
                .enumerate()
                .map(|(opcode_index, opcode)| Statement::UnhandledOpcode {
                    opcode: opcode.clone(),
                    provenance: Provenance::opcode(function_index, opcode_index),
                })
                .collect();
            return Ok(Decompiled::new(statements, diagnostics));
        }
    };

    let mut diagnostics = Vec::new();
    for &opcode_index in &graph.unreachable_instructions {
        if let Some(opcode) = function.ops.get(opcode_index) {
            diagnostics.push(Diagnostic::for_opcode(
                DiagnosticSeverity::Information,
                code,
                function_index,
                function,
                opcode_index,
                opcode,
                "instruction is unreachable from the synthetic entry node",
            ));
        }
    }
    let mut filtered;
    let input = if options.include_unreachable || graph.unreachable_instructions.is_empty() {
        function
    } else {
        filtered = function.clone();
        for &index in &graph.unreachable_instructions {
            if let Some(opcode) = filtered.ops.get_mut(index) {
                *opcode = Opcode::Nop;
            }
        }
        &filtered
    };

    let typed_ir = ir::TypedIr::build_with_cfg(code, input, graph.clone());
    diagnostics.extend(typed_ir.diagnostics);

    let legacy = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        decompile_code_legacy(code, input, function_index, &typed_ir.value)
    }));
    let (legacy_statements, flat) = match legacy {
        Ok(legacy) => {
            diagnostics.extend(legacy.diagnostics);
            (legacy.statements, legacy.flat)
        }
        Err(payload) => {
            let message = payload
                .downcast_ref::<&str>()
                .copied()
                .or_else(|| payload.downcast_ref::<String>().map(String::as_str))
                .unwrap_or("unknown decompiler panic");
            diagnostics.push(Diagnostic::fatal(
                function_index,
                format!("recovered from malformed bytecode: {message}"),
            ));
            (
                function
                    .ops
                    .iter()
                    .enumerate()
                    .map(|(opcode_index, opcode)| Statement::UnhandledOpcode {
                        opcode: opcode.clone(),
                        provenance: Provenance::opcode(function_index, opcode_index),
                    })
                    .collect(),
                FlatOutput::default(),
            )
        }
    };
    let mut statements = match structurer::structure_function(code, input, &graph, &flat) {
        Ok(structured) => {
            if structured.used_fallback {
                let message = structured
                    .fallback_reason
                    .unwrap_or_else(|| "complex CFG uses explicit state-machine output".to_owned());
                if let Some(opcode) = function.ops.first() {
                    diagnostics.push(Diagnostic::for_opcode(
                        DiagnosticSeverity::Information,
                        code,
                        function_index,
                        function,
                        0,
                        opcode,
                        message,
                    ));
                }
            }
            structured.statements
        }
        Err(error) => {
            diagnostics.push(Diagnostic::fatal(
                function_index,
                format!("structured control-flow verifier: {error}"),
            ));
            legacy_statements
        }
    };

    ast::attach_provenance(
        &mut statements,
        Provenance::new(function_index, 0, function.ops.len()),
    );
    // Once the verified region emitter owns that opcode, those diagnostics no
    // longer describe the returned AST.
    diagnostics.retain(|diagnostic| {
        diagnostic.severity != DiagnosticSeverity::Unsupported
            || function
                .ops
                .get(diagnostic.opcode_index)
                .map_or(true, |opcode| {
                    opcode_coverage(opcode).lowering != LoweringCoverage::Structural
                })
    });
    let unsupported = diagnostics.iter().any(|diagnostic| {
        matches!(
            diagnostic.severity,
            DiagnosticSeverity::Unsupported | DiagnosticSeverity::Fatal
        )
    });
    if options.mode == DecompileMode::Strict && unsupported {
        Err(DecompileError::new(diagnostics))
    } else {
        Ok(Decompiled::new(statements, diagnostics))
    }
}

/// Decompile a function out of context.
pub fn decompile_function(
    code: &Bytecode,
    function: &Function,
) -> Result<Decompiled<Method>, DecompileError> {
    decompile_function_with_options(code, function, DecompileOptions::default())
}

pub fn decompile_function_with_options(
    code: &Bytecode,
    function: &Function,
    options: DecompileOptions,
) -> Result<Decompiled<Method>, DecompileError> {
    decompile_code_with_options(code, function, options).map(|body| {
        body.map(|statements| Method {
            fun: function.findex,
            static_: true,
            dynamic: false,
            statements,
        })
    })
}

/// Decompile a class with its static and instance fields and methods.
pub fn decompile_class(
    code: &Bytecode,
    obj: &TypeObj,
) -> Result<Decompiled<Class>, DecompileError> {
    decompile_class_with_options(code, obj, DecompileOptions::default())
}

pub fn decompile_class_with_options(
    code: &Bytecode,
    obj: &TypeObj,
    options: DecompileOptions,
) -> Result<Decompiled<Class>, DecompileError> {
    let mut diagnostics = Vec::new();
    let static_type = obj
        .global
        .0
        .checked_sub(1)
        .and_then(|index| code.globals.get(index))
        .and_then(|ty| code.types.get(ty.0))
        .and_then(Type::get_type_obj);

    let mut fields = Vec::new();
    for (i, f) in obj.own_fields.iter().enumerate() {
        let field_index = if obj.fields.len() >= obj.own_fields.len() {
            i + obj.fields.len() - obj.own_fields.len()
        } else {
            i
        };

        if obj.bindings.contains_key(&RefField(field_index)) {
            continue;
        }
        fields.push(ClassField {
            name: f.name(code).to_owned(),
            static_: false,
            ty: f.t,
        });
    }
    if let Some(ty) = static_type {
        for (i, f) in ty.own_fields.iter().enumerate() {
            let field_index = if ty.fields.len() >= ty.own_fields.len() {
                i + ty.fields.len() - ty.own_fields.len()
            } else {
                i
            };

            if ty.bindings.contains_key(&RefField(field_index)) {
                continue;
            }
            fields.push(ClassField {
                name: f.name(code).to_owned(),
                static_: true,
                ty: f.t,
            });
        }
    }

    let mut method_refs: Vec<_> = obj
        .bindings
        .values()
        .copied()
        .map(|fun| (fun, false, true))
        .collect();
    if let Some(ty) = static_type {
        method_refs.extend(ty.bindings.values().copied().map(|fun| (fun, true, false)));
    }
    for f in &obj.protos {
        method_refs.push((f.findex, false, false));
    }
    method_refs.sort_by_key(|(fun, static_, dynamic)| (fun.0, *static_, *dynamic));
    method_refs.dedup();

    let mut methods = Vec::new();
    for (fun, static_, dynamic) in method_refs {
        let Some(function) = code
            .safe_get_ref_fun(fun)
            .and_then(hlbc::types::FunPtr::as_fn)
        else {
            diagnostics.push(Diagnostic::fatal(
                fun.0,
                format!("class method references missing function {}", fun.0),
            ));
            continue;
        };
        match decompile_code_with_options(code, function, options) {
            Ok(body) => {
                diagnostics.extend(body.diagnostics);
                methods.push(Method {
                    fun,
                    static_,
                    dynamic,
                    statements: body.value,
                });
            }
            Err(error) => diagnostics.extend(error.diagnostics),
        }
    }

    let name = code.strings.get(obj.name.0).cloned().ok_or_else(|| {
        DecompileError::new(vec![Diagnostic::fatal(
            0,
            format!("class name string {} is out of bounds", obj.name.0),
        )])
    })?;
    let parent = obj.super_.and_then(|reference| {
        code.types
            .get(reference.0)
            .and_then(Type::get_type_obj)
            .and_then(|parent| code.strings.get(parent.name.0))
            .cloned()
    });

    let class = Class {
        name,
        parent,
        fields,
        methods,
    };
    let unsupported = diagnostics.iter().any(|diagnostic| {
        matches!(
            diagnostic.severity,
            DiagnosticSeverity::Unsupported | DiagnosticSeverity::Fatal
        )
    });
    if options.mode == DecompileMode::Strict && unsupported {
        Err(DecompileError::new(diagnostics))
    } else {
        Ok(Decompiled::new(class, diagnostics))
    }
}

