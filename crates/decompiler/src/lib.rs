    #[test]
    fn every_opcode_has_parser_semantics_diagnostics_and_lowering_coverage() {
        let code = Bytecode::from_file("../../data/Empty.hl").unwrap();
        let template = code.function_by_name("main").unwrap();
        assert_eq!(Opcode::COUNT, Opcode::METADATA.len());
        assert_eq!(Opcode::COUNT, OPCODE_SEMANTICS.len());
        for opcode in Opcode::all_defaults() {
            let mut encoded = Vec::new();
            opcode.write(&mut encoded).unwrap();
            assert_eq!(
                Opcode::read(&mut Cursor::new(encoded)).unwrap(),
                opcode,
                "{} lacks parser round-trip support",
                opcode.name()
            );
            let metadata = opcode.metadata();
            assert_eq!(metadata.code, opcode.code());
            assert_eq!(metadata.name, opcode.name());
            assert_eq!(
                metadata.semantics,
                &OPCODE_SEMANTICS[opcode.code() as usize],
                "{} lacks aligned semantic metadata",
                opcode.name()
            );
            for register_operand in metadata
                .semantics
                .reads
                .iter()
                .chain(metadata.semantics.writes.iter())
            {
                assert!(
                    *register_operand == "this"
                        || register_operand.starts_with("reg(mode=")
                        || metadata
                            .operands
                            .iter()
                            .any(|operand| operand.name == *register_operand),
                    "{} semantic register operand {register_operand} is not declared",
                    opcode.name()
                );
            }
            assert!(matches!(
                metadata.semantics.control_flow,
                ControlFlowBehavior::Fallthrough
                    | ControlFlowBehavior::ConditionalBranch
                    | ControlFlowBehavior::UnconditionalBranch
                    | ControlFlowBehavior::Switch
                    | ControlFlowBehavior::Return
                    | ControlFlowBehavior::Throw
                    | ControlFlowBehavior::TrapSetup
                    | ControlFlowBehavior::TrapEnd
                    | ControlFlowBehavior::Label
                    | ControlFlowBehavior::CatchMarker
                    | ControlFlowBehavior::Unknown
            ));

            let coverage = opcode_coverage(&opcode);
            if coverage.lowering == LoweringCoverage::UnsupportedFallback {
                assert_eq!(coverage.diagnostics, DiagnosticCoverage::Unsupported);
            } else {
                assert_ne!(coverage.diagnostics, DiagnosticCoverage::Unsupported);
            }

            let mut function = template.clone();
            function.ops = vec![opcode.clone()];
            let result = decompile_code(&code, &function).unwrap();
            let unsupported = result.diagnostics.iter().any(|diagnostic| {
                matches!(
                    diagnostic.severity,
                    DiagnosticSeverity::Unsupported | DiagnosticSeverity::Fatal
                )
            });
            if unsupported {
                assert!(result.value.iter().any(|statement| {
                    matches!(statement, Statement::UnhandledOpcode { opcode: found, .. } if found == &opcode)
                }), "{} disappeared without UnhandledOpcode", opcode.name());
            }
            if coverage.lowering == LoweringCoverage::UnsupportedFallback {
                assert!(unsupported, "{} fallback lacks a diagnostic", opcode.name());
                assert!(result.value.iter().any(|statement| {
                    matches!(raw_statement(statement), Statement::UnhandledOpcode { opcode: found, .. } if found == &opcode)
                }), "{} fallback lacks preserved output", opcode.name());
            }
        }
    }

